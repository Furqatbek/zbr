package com.fooddelivery.courier.entity;

/**
 * Vehicle type enumeration for couriers.
 */
public enum VehicleType {
    /**
     * Walking/on foot.
     */
    WALKING,

    /**
     * Bicycle.
     */
    BICYCLE,

    /**
     * Electric bicycle/scooter.
     */
    E_BIKE,

    /**
     * Motorcycle.
     */
    MOTORCYCLE,

    /**
     * Car.
     */
    CAR,

    /**
     * Van (for large orders).
     */
    VAN
}
